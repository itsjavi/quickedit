#!/usr/bin/env bash
# Re-vendors the tree-sitter grammars pinned in grammars.json into Vendor/<name>/, then regenerates
# Vendor/NOTICES.md, Sources/QuickEditSyntax/Generated/VendoredGrammars.swift (grammar entry points and
# embedded queries) and the grammar table in Package.swift.
#
#   scripts/vendor-grammars.sh               re-vendor every grammar
#   scripts/vendor-grammars.sh json yaml     re-vendor only these grammars (everything is re-embedded)
#   scripts/vendor-grammars.sh --embed-only  only re-embed queries (after editing Queries/ overrides)
#
# Needs curl, tar, jq, rsync and swift; grammars with "generate": true also need node (npx runs the
# pinned tree-sitter CLI because upstream doesn't commit parser.c).
set -euo pipefail

PKG="$(cd "$(dirname "$0")/.." && pwd)"
LOCK="$PKG/grammars.json"
VENDOR="$PKG/Vendor"

notices() {
  {
    echo "# Vendored tree-sitter grammars"
    echo
    echo "Generated by \`scripts/vendor-grammars.sh\` from \`grammars.json\`. Each directory keeps its upstream \`LICENSE\`."
    echo "Local query overrides in \`Queries/\` are part of QuickEdit. The runtime comes from SwiftPM dependencies:"
    echo "SwiftTreeSitter (BSD-3-Clause, https://github.com/ChimeHQ/SwiftTreeSitter) and tree-sitter (MIT,"
    echo "https://github.com/tree-sitter/tree-sitter)."
    echo
    echo "| Grammar | Repository | Commit | License |"
    echo "| ------- | ---------- | ------ | ------- |"
    jq -r '.grammars[] | "| \(.name) | \(.repo) (`\(.path)`) | `\(.commit[0:12])` (\(.ref)) | \(.license) |"' "$LOCK"
  } >"$VENDOR/NOTICES.md"
}

embed() {
  notices
  swift "$PKG/scripts/embed-queries.swift" "$PKG"
}

if [[ "${1:-}" == "--embed-only" ]]; then
  embed
  exit 0
fi

for tool in curl tar jq rsync swift; do
  command -v "$tool" >/dev/null || { echo "error: $tool is required" >&2; exit 1; }
done

CLI="$(jq -r .treeSitterCLI "$LOCK")"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/quickedit-grammars.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

wanted() {
  local name="$1"
  [[ ${#ONLY[@]} -eq 0 ]] && return 0
  local n
  for n in "${ONLY[@]}"; do [[ "$n" == "$name" ]] && return 0; done
  return 1
}

# Downloads repo@commit once (several grammars share a repository) and prints its directory.
fetch() {
  local repo="$1" commit="$2"
  local dir="$WORK/$(basename "$repo")-$commit"
  if [[ ! -d "$dir" ]]; then
    mkdir -p "$dir"
    local url="${repo/https:\/\/github.com/https://codeload.github.com}/tar.gz/$commit"
    echo "  downloading $repo@${commit:0:10}" >&2
    curl -fsSL "$url" | tar -xz -C "$dir" --strip-components 1
  fi
  echo "$dir"
}

ONLY=("$@")
COUNT="$(jq '.grammars | length' "$LOCK")"
for ((i = 0; i < COUNT; i++)); do
  g="$(jq -c ".grammars[$i]" "$LOCK")"
  name="$(jq -r .name <<<"$g")"
  wanted "$name" || continue

  target="$(jq -r .target <<<"$g")"
  repo="$(jq -r .repo <<<"$g")"
  commit="$(jq -r .commit <<<"$g")"
  path="$(jq -r .path <<<"$g")"
  queries="$(jq -r .queries <<<"$g")"
  generate="$(jq -r .generate <<<"$g")"
  echo "==> $name ($repo@${commit:0:10})"

  root="$(fetch "$repo" "$commit")"
  src="$root/$path"

  if [[ "$generate" == "true" ]]; then
    command -v npx >/dev/null || { echo "error: npx is required to generate $name" >&2; exit 1; }
    echo "  generating parser.c with tree-sitter-cli@$CLI"
    (cd "$src" && npx --yes --package="tree-sitter-cli@$CLI" -- tree-sitter generate >/dev/null)
  fi
  [[ -f "$src/src/parser.c" ]] || { echo "error: $name has no src/parser.c" >&2; exit 1; }

  abi="$(sed -nE 's/^#define LANGUAGE_VERSION ([0-9]+).*/\1/p' "$src/src/parser.c")"
  if [[ -z "$abi" || "$abi" -lt 13 || "$abi" -gt 15 ]]; then
    echo "error: $name parser ABI '$abi' is outside the runtime's supported 13...15" >&2
    exit 1
  fi
  symbol="$(grep -oE 'const TSLanguage \*tree_sitter_[A-Za-z0-9_]+\(void\)' "$src/src/parser.c" | head -1 |
    sed -E 's/.*\*(tree_sitter_[A-Za-z0-9_]+)\(void\)/\1/')"
  [[ -n "$symbol" ]] || { echo "error: no tree_sitter_* entry point in $name" >&2; exit 1; }

  out="$VENDOR/$name"
  rm -rf "$out"
  mkdir -p "$out/src" "$out/queries" "$out/include"
  # Generated parser, external scanner, tree_sitter/*.h and anything the scanner includes textually.
  rsync -a --exclude '*.json' --exclude '*.wasm' --exclude '*.o' "$src/src/" "$out/src/"
  # Only highlight and injection queries are used (locals, tags, folds and indents aren't).
  for query in "$root/$queries"/highlights*.scm "$root/$queries"/injections*.scm; do
    [[ -f "$query" ]] && cp "$query" "$out/queries/"
  done
  rmdir "$out/queries" 2>/dev/null || true

  while IFS= read -r extra; do
    [[ -z "$extra" ]] && continue
    mkdir -p "$out/$(dirname "$extra")"
    cp "$root/$extra" "$out/$extra"
    # The scanner includes it relative to <path>/src; vendored sources sit one level higher.
    for c in "$out"/src/*.c; do
      sed -i '' "s#\"../../$extra\"#\"../$extra\"#" "$c"
    done
  done < <(jq -r '.extraFiles // [] | .[]' <<<"$g")

  license=""
  for candidate in LICENSE LICENSE.md LICENSE.txt LICENCE COPYING; do
    if [[ -f "$root/$candidate" ]]; then license="$candidate"; break; fi
  done
  [[ -n "$license" ]] || { echo "error: $name has no LICENSE file" >&2; exit 1; }
  cp "$root/$license" "$out/LICENSE"

  guard="$(tr '[:lower:]' '[:upper:]' <<<"$symbol")_H_"
  cat >"$out/include/$target.h" <<EOF
// Generated by scripts/vendor-grammars.sh. Do not edit.
#ifndef $guard
#define $guard

typedef struct TSLanguage TSLanguage;

#ifdef __cplusplus
extern "C" {
#endif

const TSLanguage *$symbol(void);

#ifdef __cplusplus
}
#endif

#endif
EOF
  echo "  ABI $abi, $(du -sh "$out/src" | cut -f1) of C sources"
done

embed
echo "Done. Run 'swift test --package-path $PKG' to verify the grammars and queries."
