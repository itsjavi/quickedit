// Generates Sources/QuickEditSyntax/Generated/VendoredGrammars.swift (grammar entry points and the
// composed highlight/injection queries as raw string literals) and the grammar table in Package.swift,
// from grammars.json and the vendored grammars. Run through scripts/vendor-grammars.sh.
//
// The app bundle is assembled by a shell script, so queries are compiled into the binary instead of
// being loaded from a SwiftPM resource bundle.

import Foundation

struct Lock: Decodable {
    struct Grammar: Decodable {
        let name: String
        let target: String
        let highlights: [String]
        let injections: [String]
    }

    let grammars: [Grammar]
}

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("error: \(message)\n".utf8))
    exit(1)
}

let arguments = CommandLine.arguments
guard arguments.count == 2 else { fail("usage: embed-queries.swift <package directory>") }
let package = URL(fileURLWithPath: arguments[1])
let fileManager = FileManager.default

func read(_ url: URL) -> String {
    guard let text = try? String(contentsOf: url, encoding: .utf8) else { fail("cannot read \(url.path)") }
    return text
}

let lockData = (try? Data(contentsOf: package.appendingPathComponent("grammars.json"))) ?? Data()
guard let lock = try? JSONDecoder().decode(Lock.self, from: lockData) else { fail("cannot decode grammars.json") }

/// "grammar/file.scm" → Queries/grammar/file.scm (local override) or Vendor/grammar/queries/file.scm.
func resolve(_ reference: String) -> (url: URL, label: String) {
    let parts = reference.split(separator: "/", maxSplits: 1).map(String.init)
    guard parts.count == 2 else { fail("query reference '\(reference)' must be 'grammar/file.scm'") }
    let local = package.appendingPathComponent("Queries/\(parts[0])/\(parts[1])")
    if fileManager.fileExists(atPath: local.path) { return (local, "Queries/\(reference)") }
    let vendored = package.appendingPathComponent("Vendor/\(parts[0])/queries/\(parts[1])")
    if fileManager.fileExists(atPath: vendored.path) { return (vendored, "Vendor/\(parts[0])/queries/\(parts[1])") }
    fail("query '\(reference)' not found in Queries/ or Vendor/")
}

func compose(_ references: [String]) -> String? {
    guard !references.isEmpty else { return nil }
    return references.map { reference in
        let (url, label) = resolve(reference)
        return ";; ---- \(label)\n" + read(url).trimmingCharacters(in: .whitespacesAndNewlines) + "\n"
    }.joined(separator: "\n")
}

/// A multi-line raw string literal whose delimiter can't occur in the content.
func literal(_ text: String) -> String {
    var hashes = "#"
    while text.contains("\"\"\"" + hashes) || text.contains("\\" + hashes) {
        hashes += "#"
    }
    return "\(hashes)\"\"\"\n\(text)\"\"\"\(hashes)"
}

func symbol(for grammar: Lock.Grammar) -> String {
    let header = package.appendingPathComponent("Vendor/\(grammar.name)/include/\(grammar.target).h")
    let text = read(header)
    guard let range = text.range(of: #"tree_sitter_[A-Za-z0-9_]+"#, options: .regularExpression) else {
        fail("no entry point in \(header.path)")
    }
    return String(text[range])
}

func identifier(_ name: String) -> String {
    let parts = name.split(separator: "_").map(String.init)
    return parts[0] + parts.dropFirst().map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
}

var swift = """
// Generated by scripts/vendor-grammars.sh from grammars.json. Do not edit.
// Queries are composed in grammars.json order; local overrides live in Queries/.

"""
for grammar in lock.grammars.sorted(by: { $0.target < $1.target }) {
    swift += "import \(grammar.target)\n"
}
swift += """

enum VendoredGrammars {
    static let names: [String] = [\(lock.grammars.map { "\"\($0.name)\"" }.joined(separator: ", "))]

    /// The grammar's `TSLanguage` pointer.
    static func language(named name: String) -> OpaquePointer? {
        switch name {

"""
for grammar in lock.grammars {
    swift += "        case \"\(grammar.name)\": \(symbol(for: grammar))()\n"
}
swift += """
        default: nil
        }
    }

    static func highlightsQuery(named name: String) -> String? {
        switch name {

"""
for grammar in lock.grammars where !grammar.highlights.isEmpty {
    swift += "        case \"\(grammar.name)\": \(identifier(grammar.name))Highlights\n"
}
swift += """
        default: nil
        }
    }

    static func injectionsQuery(named name: String) -> String? {
        switch name {

"""
for grammar in lock.grammars where !grammar.injections.isEmpty {
    swift += "        case \"\(grammar.name)\": \(identifier(grammar.name))Injections\n"
}
swift += """
        default: nil
        }
    }
}

"""
for grammar in lock.grammars {
    if let highlights = compose(grammar.highlights) {
        swift += "\nprivate let \(identifier(grammar.name))Highlights = \(literal(highlights))\n"
    }
    if let injections = compose(grammar.injections) {
        swift += "\nprivate let \(identifier(grammar.name))Injections = \(literal(injections))\n"
    }
}

let generated = package.appendingPathComponent("Sources/QuickEditSyntax/Generated/VendoredGrammars.swift")
try? fileManager.createDirectory(at: generated.deletingLastPathComponent(), withIntermediateDirectories: true)
do {
    try swift.write(to: generated, atomically: true, encoding: .utf8)
} catch {
    fail("cannot write \(generated.path): \(error)")
}

// Package.swift grammar table (between the markers), so the manifest changes whenever a scanner appears or
// disappears and SwiftPM re-evaluates it.
let manifestURL = package.appendingPathComponent("Package.swift")
let manifest = read(manifestURL)
let begin = "// BEGIN GENERATED GRAMMARS (scripts/vendor-grammars.sh)\n"
let end = "// END GENERATED GRAMMARS\n"
guard let beginRange = manifest.range(of: begin), let endRange = manifest.range(of: end),
    beginRange.upperBound <= endRange.lowerBound
else { fail("Package.swift lacks the generated grammar markers") }
var table = "let grammars: [Grammar] = [\n"
for grammar in lock.grammars {
    let scanner = fileManager.fileExists(atPath: package.appendingPathComponent("Vendor/\(grammar.name)/src/scanner.c").path)
    table += "    Grammar(target: \"\(grammar.target)\", directory: \"\(grammar.name)\", hasScanner: \(scanner)),\n"
}
table += "]\n"
let updated = manifest.replacingCharacters(in: beginRange.upperBound..<endRange.lowerBound, with: table)
if updated != manifest {
    do {
        try updated.write(to: manifestURL, atomically: true, encoding: .utf8)
    } catch {
        fail("cannot write Package.swift: \(error)")
    }
}
print("Embedded queries for \(lock.grammars.count) grammars into \(generated.lastPathComponent)")
